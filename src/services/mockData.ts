// Helper: Calculate Lao Personal Income Tax based on Lao Tax Law brackets
export function calculateLaoTax(taxableIncome: number): number {
  if (taxableIncome <= 1300000) return 0;

  let tax = 0;
  let remaining = taxableIncome;

  // Bracket 1: 0 - 1,300,000 (0%)
  remaining -= 1300000;

  // Bracket 2: 1,300,001 - 5,000,000 (5%) -> span 3,700,000
  const b2 = Math.min(remaining, 3700000);
  tax += b2 * 0.05;
  remaining -= b2;
  if (remaining <= 0) return Math.round(tax);

  // Bracket 3: 5,000,001 - 15,000,000 (10%) -> span 10,000,000
  const b3 = Math.min(remaining, 10000000);
  tax += b3 * 0.10;
  remaining -= b3;
  if (remaining <= 0) return Math.round(tax);

  // Bracket 4: 15,000,001 - 25,000,000 (15%) -> span 10,000,000
  const b4 = Math.min(remaining, 10000000);
  tax += b4 * 0.15;
  remaining -= b4;
  if (remaining <= 0) return Math.round(tax);

  // Bracket 5: 25,000,001 - 65,000,000 (20%) -> span 40,000,000
  const b5 = Math.min(remaining, 40000000);
  tax += b5 * 0.20;
  remaining -= b5;
  if (remaining <= 0) return Math.round(tax);

  // Bracket 6: > 65,000,000 (25%)
  tax += remaining * 0.25;

  return Math.round(tax);
}

// Helper: Calculate Lao Social Security Organization (LSSO) 5.5% employee contribution capped at 4,500,000 LAK ceiling
export function calculateLaoSocialSecurity(grossSalary: number): { employeeSS: number; employerSS: number } {
  const maxCap = 4500000; // Lao ceiling cap
  const baseForSS = Math.min(grossSalary, maxCap);
  const employeeSS = Math.round(baseForSS * 0.055); // 5.5%
  const employerSS = Math.round(baseForSS * 0.060); // 6.0%
  return { employeeSS, employerSS };
}

export function generatePayslipsForEmployees(employees: Employee[], periodId: string): Payslip[] {
  return employees.map((emp) => {
    const baseSalary = emp.baseSalary;
    const allowances = 1500000; // standard state enterprise transport and meal allowance
    const grossSalary = baseSalary + allowances;
    const { employeeSS, employerSS } = calculateLaoSocialSecurity(grossSalary);
    // Taxable income is Gross minus employee social security
    const taxableIncome = Math.max(0, grossSalary - employeeSS);
    const personalIncomeTax = calculateLaoTax(taxableIncome);
    const otherDeductions = 0;
    const netPay = grossSalary - employeeSS - personalIncomeTax - otherDeductions;

    return {
      id: `ps-${periodId}-${emp.id}`,
      payrollPeriodId: periodId,
      employeeId: emp.id,
      baseSalary,
      allowances,
      grossSalary,
      socialSecurityEmployee: employeeSS,
      socialSecurityEmployer: employerSS,
      taxableIncome,
      personalIncomeTax,
      otherDeductions,
      netPay,
      paymentStatus: 'PAID',
      bankAccountMasked: emp.bankAccountNumber ? `••••-••••-${emp.bankAccountNumber.slice(-4)}` : undefined,
      calculatedAt: '2026-10-01T10:00:00Z',
    };
  });
}

